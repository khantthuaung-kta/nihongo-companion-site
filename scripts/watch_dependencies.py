"""Record upstream dependency releases for upgrade planning, without modifying app dependencies.

This is a changelog-style snapshot, not an automatic package upgrade. Failed API
requests keep previously collected results so temporary outages cause no false diffs.
"""
from __future__ import annotations

import json
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.parse import quote
from urllib.request import Request, urlopen

PACKAGES = (
    ("Python", "fastapi", "https://pypi.org/pypi/fastapi/json"),
    ("Python", "sqlalchemy", "https://pypi.org/pypi/SQLAlchemy/json"),
    ("JavaScript", "react", "https://registry.npmjs.org/react/latest"),
    ("JavaScript", "vite", "https://registry.npmjs.org/vite/latest"),
    ("JavaScript", "tailwindcss", "https://registry.npmjs.org/tailwindcss/latest"),
)
SNAPSHOT = Path("data/upstream-dependencies.json")
REPORT = Path("docs/dependency-release-watch.md")


def fetch_version(ecosystem: str, name: str, url: str) -> dict[str, str]:
    request = Request(url, headers={"Accept": "application/json", "User-Agent": "nihongo-companion-release-watch"})
    with urlopen(request, timeout=20) as response:
        result = json.load(response)
    version = result["info"]["version"] if ecosystem == "Python" else result["version"]
    if not isinstance(version, str) or not version.strip():
        raise ValueError("Missing package version")
    return {"ecosystem": ecosystem, "version": version, "source": url}


def main() -> int:
    previous = json.loads(SNAPSHOT.read_text(encoding="utf-8")) if SNAPSHOT.exists() else {}
    current = dict(previous)
    success = 0
    for ecosystem, name, url in PACKAGES:
        try:
            current[name] = fetch_version(ecosystem, name, url)
            success += 1
        except (HTTPError, URLError, TimeoutError, ValueError, KeyError, json.JSONDecodeError) as error:
            print(f"Warning: {name}: {error}; keeping previous version")
    if success == 0:
        print("All registries failed; skipping changes.")
        return 1

    current = {name: current[name] for name in sorted(current)}
    if current == previous:
        print("No upstream package release changes.")
        return 0

    lines = [
        "# Dependency release watch",
        "",
        "Latest published versions for packages relevant to Nihongo Companion.",
        "**Informational only:** these are NOT necessarily the versions installed by this app.",
        "Review compatibility and run tests before upgrading dependencies.",
        "",
        "| Ecosystem | Package | Latest published version | Registry |",
        "| --- | --- | --- | --- |",
    ]
    for name, info in current.items():
        lines.append(f"| {info['ecosystem']} | \`{name}\` | \`{info['version']}\` | [Source]({info['source']}) |")
    lines.extend(["", "Generated by \`scripts/watch_dependencies.py\`. Only changes when upstream versions change.", ""])
    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT.write_text(json.dumps(current, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Updated package release watch ({success} sources checked successfully).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
